// IPv4 문자열 → 부호 없는 32비트 정수. 아니면 null.
function toInt(ip) {
  if (typeof ip !== 'string') return null;
  const p = ip.split('.');
  if (p.length !== 4) return null;
  let n = 0;
  for (const o of p) {
    const x = Number(o);
    if (!Number.isInteger(x) || x < 0 || x > 255) return null;
    n = n * 256 + x;
  }
  return n >>> 0;
}

// CIDR 을 {base, mask, label} 로 미리 계산해 둔다.
const RANGES = [];
for (const g of GROUPS) {
  for (const cidr of g.cidrs) {
    const [ip, bitsStr] = cidr.split('/');
    const bits = Number(bitsStr);
    const mask = bits === 0 ? 0 : (0xFFFFFFFF << (32 - bits)) >>> 0;
    RANGES.push({ base: (toInt(ip) & mask) >>> 0, mask, label: g.label });
  }
}

// x-forwarded-for 에 포트가 붙어 오면 앞부분만 본다. IPv6·이상값은 null.
function normalize(ip) {
  const clean = typeof ip === 'string' ? ip.trim().replace(/:\d+$/, '') : ip;
  return toInt(clean);
}

export function isDatacenterIp(ip) {
  const n = normalize(ip);
  if (n === null) return false;
  for (const r of RANGES) {
    if (((n & r.mask) >>> 0) === r.base) return true;
  }
  return false;
}

// 데이터센터/클라우드면 업체 라벨, 아니면 null.
export function datacenterLabel(ip) {
  const n = normalize(ip);
  if (n === null) return null;
  for (const r of RANGES) {
    if (((n & r.mask) >>> 0) === r.base) return r.label;
  }
  return null;
}

