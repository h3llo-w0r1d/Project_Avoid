export function isCloudOrg(org) {
  if (!org) return false;
  const s = org.toLowerCase();
  return CLOUD_KW.some((k) => s.includes(k));
}

// 큰 클라우드는 보기 좋은 짧은 이름으로. 없으면 ''.
const PRETTY = [
  ['google', 'Google'], ['amazon', 'AWS'], ['aws', 'AWS'], ['microsoft', 'Azure'],
  ['azure', 'Azure'], ['digitalocean', 'DigitalOcean'], ['digital ocean', 'DigitalOcean'],
  ['tencent', 'Tencent Cloud'], ['alibaba', 'Alibaba Cloud'], ['aliyun', 'Alibaba Cloud'],
  ['ovh', 'OVH'], ['hetzner', 'Hetzner'], ['contabo', 'Contabo'], ['linode', 'Linode'],
  ['akamai', 'Linode'], ['vultr', 'Vultr'], ['cloudflare', 'Cloudflare'], ['oracle', 'Oracle Cloud']
];

export function cloudNameFromOrg(org) {
  if (!org) return '';
  const s = org.toLowerCase();
  for (const [k, v] of PRETTY) if (s.includes(k)) return v;
  return '';
}

// 조직명을 짧게 정리한다(법인 접미사 제거, 길이 제한).
export function shortOrg(org) {
  if (!org) return '';
  let s = org.replace(/,?\s+\b(LLC|Inc\.?|Ltd\.?|GmbH|B\.?V\.?|S\.?A\.?|Co\.?,?\s*Ltd\.?|AB|AS|C\.?A\.?)\.?$/i, '').trim();
  if (s.length > 26) s = s.slice(0, 26) + '…';
  return s;
}
